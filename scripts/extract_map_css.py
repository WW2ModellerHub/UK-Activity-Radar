"""Split map/marker rules out of the legacy stylesheets.

The flat redesign replaces the application chrome stylesheet, but the map
markers (trains, aircraft silhouettes, coincident-train fans, motorway signs)
are intricate and already correct on a map. This keeps exactly those rules,
in their original order, so the chrome can be rewritten without touching how
live objects are drawn.

Usage: python scripts/extract_map_css.py OUT.css IN.css [IN.css ...]
"""
from __future__ import annotations

import re
import sys

MAP_SELECTOR = re.compile(
    r"marker|leaflet|aerial|aircraft|airframe|map-[a-z]+-svg|motion-(?:shell|pointer|speed)|"
    r"train-coincident|rotor|tail-(?:boom|rotor|plane|detail)|stub-wing|jet-intake|prop-(?:hub|line)|"
    r"cockpit|live-object|maplibre|traffic-swatch|vms-display|motorway-sign|uk-speed-roundel|"
    r"\.dot\b|\.gps\b|\.report\b|\.estimate\b|heatmap|cluster|train-full-route|train-published-route|"
    r"rail-leg|selected-trail|route-guide|leg-guide|map-zooming|route-arrow|progress-line|"
    r"journey-route-line|train-live-leg|route-outline"
)
# Chrome components that happen to mention a keyword above but are restyled
# from scratch in the new stylesheet.
CHROME_ONLY = re.compile(r"activity-tooltip|tooltip-|map-legend|v12-|focus-map|detail-|workspace|panel")


def parse(css: str):
    """Yield (prelude, body) pairs for top-level statements; body None for ';' statements."""
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    i, n = 0, len(css)
    while i < n:
        j = i
        while j < n and css[j] not in "{;":
            j += 1
        if j >= n:
            break
        prelude = css[i:j].strip()
        if css[j] == ";":
            yield prelude, None
            i = j + 1
            continue
        depth, k = 1, j + 1
        while k < n and depth:
            if css[k] == "{":
                depth += 1
            elif css[k] == "}":
                depth -= 1
            k += 1
        yield prelude, css[j + 1:k - 1]
        i = k


def keep_selector(selector: str) -> bool:
    return bool(MAP_SELECTOR.search(selector)) and not CHROME_ONLY.search(selector)


def filter_block(css: str, keyframes_used: set[str]) -> list[str]:
    out: list[str] = []
    for prelude, body in parse(css):
        if body is None or not prelude:
            continue
        if prelude.startswith("@keyframes") or prelude.startswith("@-webkit-keyframes"):
            out.append(("KEYFRAMES", prelude.split()[1], f"{prelude}{{{body}}}"))
            continue
        if prelude.startswith("@media") or prelude.startswith("@supports"):
            inner = filter_block(body, keyframes_used)
            rules = [item for item in inner if isinstance(item, str)]
            if rules:
                out.append(f"{prelude}{{{''.join(rules)}}}")
            out.extend(item for item in inner if not isinstance(item, str))
            continue
        if prelude.startswith("@"):
            continue
        selectors = [part.strip() for part in prelude.split(",")]
        kept = [part for part in selectors if keep_selector(part)]
        if kept:
            out.append(f"{','.join(kept)}{{{body.strip()}}}")
            for name in re.findall(r"animation(?:-name)?\s*:\s*([A-Za-z0-9_-]+)", body):
                keyframes_used.add(name)
    return out


def main() -> None:
    target, sources = sys.argv[1], sys.argv[2:]
    keyframes_used: set[str] = set()
    rules: list[str] = []
    keyframes: dict[str, str] = {}
    for path in sources:
        for item in filter_block(open(path, encoding="utf-8").read(), keyframes_used):
            if isinstance(item, str):
                rules.append(item)
            else:
                keyframes[item[1]] = item[2]
    used = [text for name, text in keyframes.items() if name in keyframes_used]
    header = "/* Map and live-object marker styles, carried over unchanged from the v1.5 stylesheets.\n   Generated by scripts/extract_map_css.py; application chrome lives in app.css. */\n"
    with open(target, "w", encoding="utf-8") as handle:
        handle.write(header + "\n".join(rules + used) + "\n")
    print(f"{len(rules)} rules, {len(used)} keyframes -> {target}")


if __name__ == "__main__":
    main()
